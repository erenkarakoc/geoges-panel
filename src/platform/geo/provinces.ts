export type Province = (typeof PROVINCES)[number];

const known = new Set<string>(PROVINCES);

export function isProvince(value: string): value is Province {
  return known.has(value);
}

/** An optional province: empty becomes null, anything else must be one of the 81 names. */
export const optionalProvince = z
  .string()
  .trim()
  .refine((value) => value === "" || known.has(value), "İl listeden seçilmeli.")
  .transform((value) => value || null)
  .nullish();
